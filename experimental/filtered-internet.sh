#!/usr/bin/env bash
# Experimental SwitchNest filtered internet mode. Not a security guarantee.
set -Eeuo pipefail
export PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin
CONF=/etc/steamdeck-switch2
SETTINGS=$CONF/settings.sh
DNS=$CONF/dnsmasq.conf
TABLE=steamdeck_switch2_offline
NAT=steamdeck_switch2_filtered_nat
DNS_UNIT=steamdeck-switch2-dnsmasq.service
HOTSPOT_UNIT=steamdeck-switch2-hotspot.service
BACKUP=$CONF/dnsmasq.offline.backup
STATE=$CONF/filtered-mode.state
AP_IP=10.42.60.1
fail(){ echo "ERROR: $*" >&2; exit 1; }
[[ $EUID == 0 ]] || fail "Run with sudo."
[[ -f $SETTINGS && -f $DNS ]] || fail "Install SwitchNest v7.1 backend first."
# Trusted root-owned settings generated by SwitchNest. Never source user input.
[[ $(stat -c %u "$SETTINGS") == 0 && ! -L $SETTINGS ]] || fail "Untrusted settings."
# shellcheck disable=SC1090
source "$SETTINGS"
[[ ${IFACE:-} =~ ^[a-zA-Z0-9_.-]+$ ]] || fail "Invalid hotspot interface."
[[ ${BACKEND:-} == host || ${BACKEND:-} == podman ]] || fail "Unsupported DNS backend."
[[ -f $CONF/manager.sh ]] || fail "SwitchNest manager missing."
[[ $(stat -c %u "$CONF/manager.sh") == 0 ]] || fail "Untrusted manager."
command -v nft >/dev/null && command -v nmcli >/dev/null || fail "Missing nft/nmcli."
dns_restart(){ systemctl restart "$DNS_UNIT"; }
offline(){
  [[ -e $STATE ]] || { echo "Already offline (no filtered-mode state)."; exit 0; }
  # Stop forwarding first, before restoring DNS.
  nft delete table ip "$NAT" 2>/dev/null || true
  nft delete table inet "$TABLE" 2>/dev/null || true
  nft add table inet "$TABLE"
  nft 'add chain inet steamdeck_switch2_offline forward { type filter hook forward priority -100; policy accept; }'
  nft add rule inet "$TABLE" forward iifname "$IFACE" counter drop
  nft add rule inet "$TABLE" forward oifname "$IFACE" counter drop
  [[ -f $BACKUP ]] || fail "Offline DNS backup missing; forwarding remains blocked."
  cp "$BACKUP" "$DNS"
  dns_restart || fail "Offline DNS restart failed; forwarding remains blocked."
  rm -f "$STATE" "$BACKUP"
  echo "Offline DNS and forwarding guard restored. Host ip_forward sysctl not changed."
}
filtered(){
  [[ ! -e $STATE ]] || fail "Filtered mode already enabled."
  [[ $# -eq 1 ]] || fail "Usage: sudo bash $0 enable <ethernet-interface>"
  local wan=$1
  [[ $wan =~ ^[a-zA-Z0-9_.-]+$ && $wan != "$IFACE" ]] || fail "Invalid uplink."
  [[ -d /sys/class/net/$wan ]] || fail "Uplink interface missing."
  [[ $(nmcli -g GENERAL.STATE device show "$IFACE" 2>/dev/null) == *connected* ]] || fail "Hotspot is not connected."
  [[ $(nmcli -g GENERAL.STATE device show "$wan" 2>/dev/null) == *connected* ]] || fail "Uplink is not connected."
  [[ $(sysctl -n net.ipv4.ip_forward) == 1 ]] || fail "Enable IPv4 forwarding explicitly first: sudo sysctl -w net.ipv4.ip_forward=1 (revert after test)."
  [[ -f $DNS && ! -L $DNS ]] || fail "DNS config missing or symlinked."
  [[ $(stat -c %u "$DNS") == 0 ]] || fail "DNS config must be root-owned."
  [[ $(grep -c '^address=/#/10.42.60.1$' "$DNS" || true) == 1 ]] || fail "Expected offline wildcard DNS not found."
  [[ ! -e $BACKUP ]] || fail "Existing backup detected; do not overwrite."
  # Local blocklist: conservative initial coverage, not a comprehensive 90DNS list.
  cp -p "$DNS" "$BACKUP"
  python3 - "$DNS" <<'PY'
from pathlib import Path
import sys
p=Path(sys.argv[1])
lines=[x for x in p.read_text().splitlines() if x not in ("address=/#/10.42.60.1", "local=/#/")]
lines += [
 "server=1.1.1.1", "server=9.9.9.9",
 "address=/nintendo.net/0.0.0.0",
 "address=/nintendo.com/0.0.0.0",
 "address=/nintendowifi.net/0.0.0.0",
 "address=/nintendo-europe.com/0.0.0.0",
 "address=/nintendo.co.jp/0.0.0.0",
 "address=/nintendo.co.uk/0.0.0.0",
 "address=/nintendo.jp/0.0.0.0",
 "address=/nintendo.com.au/0.0.0.0",
]
p.write_text("\n".join(lines)+"\n")
PY
  if ! dns_restart; then cp "$BACKUP" "$DNS"; dns_restart || true; fail "DNS restart failed; reverted DNS."; fi
  # The existing offline guard is replaced in one nft transaction. No IPv6 forwarding is enabled.
  local rules
  rules=$(mktemp)
  chmod 600 "$rules"
  cat > "$rules" <<EOF
delete table inet $TABLE
add table inet $TABLE
add chain inet $TABLE forward { type filter hook forward priority -100; policy drop; }
add rule inet $TABLE forward iifname "$IFACE" oifname "$wan" ip saddr 10.42.60.0/24 ip protocol udp udp dport 53 counter drop
add rule inet $TABLE forward iifname "$IFACE" oifname "$wan" ip saddr 10.42.60.0/24 ip protocol tcp tcp dport { 53, 853 } counter drop
add rule inet $TABLE forward iifname "$IFACE" oifname "$wan" ip saddr 10.42.60.0/24 ct state new,established,related counter accept
add rule inet $TABLE forward iifname "$wan" oifname "$IFACE" ip daddr 10.42.60.0/24 ct state established,related counter accept
add table ip $NAT
add chain ip $NAT postrouting { type nat hook postrouting priority 100; policy accept; }
add rule ip $NAT postrouting ip saddr 10.42.60.0/24 oifname "$wan" masquerade
EOF
  if nft list table ip "$NAT" >/dev/null 2>&1; then
    cp "$BACKUP" "$DNS"; dns_restart || true; rm -f "$rules"; fail "NAT table already exists."
  fi
  if ! nft -c -f "$rules" || ! nft -f "$rules"; then
    rm -f "$rules"
    cp "$BACKUP" "$DNS"; dns_restart || true
    fail "Firewall activation failed. Check guard with: sudo nft list table inet $TABLE"
  fi
  rm -f "$rules"
  printf 'WAN=%s\n' "$wan" > "$STATE"
  chmod 600 "$STATE"
  echo "EXPERIMENTAL filtered IPv4 internet mode active via $wan."
  echo "Nintendo blocking is INCOMPLETE; encrypted DNS, direct IP and other bypasses remain possible."
  echo "Run: sudo bash $0 disable to restore offline mode."
}
case ${1:-} in
  enable) shift; filtered "$@" ;;
  disable) offline ;;
  status) [[ -f $STATE ]] && echo "Experimental filtered mode active" || echo "No filtered-mode state (expected offline)" ;;
  *) echo "Usage: sudo bash $0 enable <ethernet-interface>|disable|status"; exit 2 ;;
esac
